import { expect, test, type Page } from '@playwright/test'
import { startLocalServers, stopLocalServers } from './local-servers.ts'
import { E2E_PASSWORD } from './fixtures.ts'
test.beforeAll(async () => { test.setTimeout(120_000); await startLocalServers() })
test.afterAll(stopLocalServers)
async function login(page: Page, email: string, password = E2E_PASSWORD) {
  await page.goto('/login')
  await page.getByLabel(/^Email/).fill(email)
  await page.getByLabel(/^Mật khẩu/).fill(password)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
}
async function token(page: Page) {
  return page.evaluate(() => JSON.parse(sessionStorage.getItem('gomnang.httpSession.v1')!).token as string)
}
async function openLogout(page: Page) {
  await page.getByRole('button', { name: /^Tài khoản:/ }).click()
  await page.getByRole('menuitem', { name: 'Đăng xuất', exact: true }).click()
}
test('admin creates verifier; reviewer can work immediately and optionally change password', async ({ page }, info) => {
  await login(page, 'admin@e2e.test')
  await expect(page).toHaveURL(/\/admin\/verifiers$/)
  await page.getByLabel(/^Họ và tên/).fill('Verifier Browser')
  await page.getByLabel(/^Email người kiểm duyệt/).fill('browser-verifier@e2e.test')
  await page.getByLabel(/^Mật khẩu/).fill(E2E_PASSWORD)
  await page.getByLabel(/^Xác nhận mật khẩu/).fill(E2E_PASSWORD)
  await page.getByRole('button', { name: 'Tạo tài khoản kiểm duyệt', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Đã tạo tài khoản browser-verifier@e2e.test' })).toBeVisible()
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('admin-verifiers-mobile.png'), fullPage: true })
  await openLogout(page)
  await login(page, 'browser-verifier@e2e.test')
  await expect(page).toHaveURL(/\/verify$/)
  const oldToken = await token(page)
  expect((await page.request.get('/api/verification-queue', { headers: { authorization: 'Bearer ' + oldToken } })).status()).toBe(200)
  await page.getByRole('button', { name: /^Tài khoản:/ }).click()
  await page.getByRole('menuitem', { name: 'Đổi mật khẩu', exact: true }).click()
  await expect(page).toHaveURL(/\/change-password$/)
  await page.getByLabel(/^Mật khẩu hiện tại/).fill(E2E_PASSWORD)
  await page.getByLabel(/^Mật khẩu mới/).fill('New-private-browser-password2')
  await page.getByLabel(/^Xác nhận mật khẩu mới/).fill('New-private-browser-password2')
  await page.getByRole('button', { name: 'Đổi mật khẩu và tiếp tục' }).click()
  await expect(page).toHaveURL(/\/verify$/)
  await expect(page.getByRole('heading', { name: 'Hàng chờ xác minh' })).toBeVisible()
  expect((await page.request.get('/api/auth/me', { headers: { authorization: 'Bearer ' + oldToken } })).status()).toBe(401)
  const full = await token(page)
  expect((await page.request.get('/api/admin/verifiers', { headers: { authorization: 'Bearer ' + full } })).status()).toBe(403)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Tài khoản: Verifier Browser' })).toBeVisible()
})
test('Google callback cookie passes through Next rewrite and completes once as ordinary user', async ({ page }) => {
  let completions = 0
  page.on('request', (r) => { if (r.url().includes('/api/auth/google/complete')) completions++ })
  await page.goto('/login')
  await expect(page.getByText('Dùng tài khoản mẫu', { exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Đăng nhập bằng Google' }).click()
  await expect(page.getByRole('button', { name: 'Tài khoản: Google E2E' })).toBeVisible()
  expect(completions).toBe(1)
  const current = await token(page)
  expect((await page.request.get('/api/admin/verifiers', { headers: { authorization: 'Bearer ' + current } })).status()).toBe(403)
  await expect(page.getByRole('navigation').getByRole('link', { name: 'Hàng chờ xác minh' })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Tài khoản: Google E2E' })).toBeVisible()
})
test('logout failure keeps session and supports retry; acknowledged logout revokes token', async ({ page }) => {
  await login(page, 'admin@e2e.test')
  await expect(page).toHaveURL(/\/admin\/verifiers$/)
  const copied = await token(page)
  await page.route('**/api/auth/logout', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'TEST_FAILURE', message: 'Thử lại.' } }) }))
  await openLogout(page)
  await expect(page.getByRole('alert').filter({ hasText: 'Chưa xác nhận đăng xuất' })).toBeVisible()
  expect(await token(page)).toBe(copied)
  expect((await page.request.get('/api/auth/me', { headers: { authorization: 'Bearer ' + copied } })).status()).toBe(200)
  await page.unroute('**/api/auth/logout')
  await page.getByRole('menuitem', { name: 'Đăng xuất', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Đăng nhập', exact: true })).toBeVisible()
  expect((await page.request.get('/api/auth/me', { headers: { authorization: 'Bearer ' + copied } })).status()).toBe(401)
})
